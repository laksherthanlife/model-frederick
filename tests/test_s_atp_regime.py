    @pytest.mark.parametrize("name", sorted(MAINTENANCE_REGIMES))
    @pytest.mark.parametrize("field, column", [
        ("growth_at_zero_ngam_per_h", "growth_at_zero_ngam_per_h"),
        ("ethanol_at_zero_ngam_mmol_per_gdcw_h", "ethanol_at_zero_ngam_mmol_per_gdcw_h"),
        ("ngam_growth_slope_per_h_per_mmol_atp", "ngam_slope_per_h_per_mmol_atp"),
        ("no_growth_ngam_mmol_atp_per_gdw_h", "no_growth_ngam_mmol_atp_per_gdw_h"),
        ("slope_linearity_growth_error_per_h", "slope_linearity_growth_error_per_h"),
    ])
    def test_the_shipped_value_is_the_cell(self, table, name, field, column):
        regime = MAINTENANCE_REGIMES[name]

        assert getattr(regime, field) == pytest.approx(_row(table, regime)[column])

    @pytest.mark.parametrize("name", sorted(MAINTENANCE_REGIMES))
    def test_the_shipped_label_is_the_cell(self, table, name):
        regime = MAINTENANCE_REGIMES[name]

        assert regime.regime == _row(table, regime)["regime"]

    def test_the_table_sweeps_oxygen_and_not_only_glucose(self, table):
        """The defect that produced the wrong branch: one bound varied, the other printed."""
        assert table["oxygen_lower_bound_mmol_per_gdcw_h"].nunique() > 1
        assert table["glucose_lower_bound_mmol_per_gdcw_h"].nunique() > 1

    def test_the_table_contains_both_regimes(self, table):
        assert set(table["regime"]) == {"respiratory", "fermentative"}

    def test_the_table_names_the_floor_it_is_judged_against(self, table):
        assert (table["growth_assay_floor_per_h"] == MEASURED_GROWTH_RATE_SE).all()

