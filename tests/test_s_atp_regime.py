        assert (REFERENCE_REGIME.glucose_lower_bound_mmol_per_gdcw_h
                == -REFERENCE_AEROBIC_BATCH.glucose_uptake)
        assert (REFERENCE_REGIME.oxygen_lower_bound_mmol_per_gdcw_h
                == -REFERENCE_AEROBIC_BATCH.oxygen_uptake)

