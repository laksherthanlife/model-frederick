class TestItRefusesRatherThanInterpolating:
    """Criterion (b). Every regime here is a solved point; a point between two of them is not
    a regime, because the slope steps when overflow switches on."""

    def test_an_unsolved_operating_point_is_refused(self):
        with pytest.raises(KeyError, match="REFUSED"):
            regime_for(-5.0, -2.5)

    def test_the_refusal_names_the_points_that_do_exist_and_how_to_add_one(self):
        with pytest.raises(KeyError, match="maintenance_scale.py"):
            regime_for(-5.0, -2.5)

    @pytest.mark.parametrize("oxygen", [-0.5, -5.0, -100.0])
    def test_a_96_well_plate_is_refused_because_nobody_measured_its_oxygen(self, oxygen):
        """The caveat this correction ships with. A shaken 96-well plate has no measured kLa
        in this repository, so its oxygen uptake bound is unknown -- and since the slope
        steps at the onset of overflow, an unknown oxygen bound is a REFUSAL and not the
        nearest solved point, at the reference glucose as much as anywhere else."""
        with pytest.raises(KeyError, match="REFUSED"):
            regime_for(-REFERENCE_AEROBIC_BATCH.glucose_uptake, oxygen)

    def test_a_solved_point_resolves(self):
        assert regime_for(-10.0, -1000.0).name == "respiratory_glucose_excess"
        assert regime_for(-REFERENCE_AEROBIC_BATCH.glucose_uptake,
                          -REFERENCE_AEROBIC_BATCH.oxygen_uptake) is REFERENCE_REGIME

    def test_a_growth_penalty_without_a_regime_is_a_refusal_and_not_a_default(self):
        result = maintenance_from_reporter(1.0, 1.0)

        assert isinstance(result.growth_penalty_per_h, Refused)

    def test_that_refusal_raises_on_float_rather_than_evaluating(self):
        result = maintenance_from_reporter(1.0, 1.0)

        with pytest.raises(TypeError, match="REFUSED"):
            float(result.growth_penalty_per_h)

    def test_the_refusal_is_falsey_so_a_truth_test_cannot_mistake_it_for_a_number(self):
        assert not Refused("because")

    def test_the_refusal_says_how_big_the_thing_it_will_not_guess_is(self):
        """A refusal that does not say what it is worth is an obstacle, not a finding."""
        result = maintenance_from_reporter(1.0, 1.0)

        assert "2.32x" in repr(result.growth_penalty_per_h)

    def test_supplying_a_regime_lifts_it(self):
        result = maintenance_from_reporter(1.0, 1.0, regime=REFERENCE_REGIME)
        low, high = result.growth_penalty_per_h

        assert 0 < low <= high

    def test_the_two_regimes_give_different_growth_costs_for_the_same_reading(self):
        """End to end: the same reporter reading, two operating points, two answers. This is
        the behaviour the whole change exists to produce."""
        fermenting = maintenance_from_reporter(1.0, 1.0, regime=REFERENCE_REGIME)
        respiring = maintenance_from_reporter(
            1.0, 1.0, regime=MAINTENANCE_REGIMES["respiratory_glucose_excess"])

        assert (fermenting.growth_penalty_per_h[1]
                > 2 * respiring.growth_penalty_per_h[1])

    def test_the_summary_says_which_regime_priced_it(self):
        text = maintenance_from_reporter(1.0, 1.0, regime=REFERENCE_REGIME).summary()

        assert "aerobic_batch_reference" in text

    def test_the_summary_quotes_no_growth_cost_when_nothing_priced_it(self):
        """It reports the NGAM interval and stops. The refusal lives on
        :attr:`growth_penalty_per_h`, which raises on ``float``; putting it in the summary
        too would put the word REFUSED into every regime-free line and would collide with
        `tests/test_stress_energetics.py`, where REFUSED means the NGAM value is unusable."""
        assert "growth" not in maintenance_from_reporter(1.0, 1.0).summary()

    def test_a_bound_past_the_no_growth_threshold_is_refused(self):
        """Extrapolating a linear penalty past the threshold returns more growth lost than
        there is growth. The LP is infeasible there, which is not the same as slow."""
        with pytest.raises(ValueError, match="no-growth threshold"):
            REFERENCE_REGIME.growth_penalty_per_h(
                REFERENCE_REGIME.no_growth_ngam_mmol_atp_per_gdw_h + 1.0)

    def test_a_negative_bound_is_refused(self):
        with pytest.raises(ValueError, match="non-negative"):
            REFERENCE_REGIME.growth_penalty_per_h(-1.0)


