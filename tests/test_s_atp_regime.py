"""The NGAM -> growth slope is a function of the regime, and these pin every half of that.

s_ATP was carried in `bridge/maintenance_calibration.py` and `bridge/stress_energetics.py` as
one number, 0.004642 /h per mmol ATP/gDW/h, tagged MEASURED, and defended by an invariance:
identical at glucose -1.0, -1.5 and -10.0. The invariance was real. Every row it was measured
on had ``oxygen_lower_bound = -1000.0`` and secreted no ethanol, so it was measured across the
carbon supply on a fully respiratory cell -- the one axis that does not move the slope.

At `fba/physiology.REFERENCE_AEROBIC_BATCH`, the operating point this repository validates its
GEM against, the cell ferments and the slope is 2.32x larger. Four things follow and each has
tests below:

  * the slope is per-regime and the regimes are SOLVED, not asserted -- so they are checked
    against `outputs/maintenance_scale.csv` cell by cell, and against Yeast9 itself under
    ``integration``;
  * the ablation is stated against a named floor, `MEASURED_GROWTH_RATE_SE`, INCLUDING the
    half where it fails -- at the measured maintenance total the regime is not resolvable;
  * a point nobody solved is REFUSED rather than interpolated, because the slope steps;
  * the tag is MODEL-DERIVED / IN_SILICO, and a test fails if anything calls it measured.
"""

