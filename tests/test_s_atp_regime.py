GLUCOSE_EXCHANGE = "r_1714"
OXYGEN_EXCHANGE = "r_1992"
ETHANOL_EXCHANGE = "r_1761"

#: The two NGAM totals the latent branch spans: the measured full-stress maintenance and the
#: envelope `latent_bridge` asserts. Both from the modules, neither retyped.
MEASURED_TOTAL = maintenance_from_reporter(1.0, 1.0).ngam_high
ASSERTED_TOTAL = 7.2


@pytest.fixture(scope="module")
def table():
    """`outputs/maintenance_scale.csv`, or a skip. Regenerated by scripts/maintenance_scale.py."""
    import pandas as pd

    path = pathlib.Path(paths.REPO_ROOT) / "outputs" / "maintenance_scale.csv"
    if not path.exists():
        pytest.skip("outputs/maintenance_scale.csv absent; run scripts/maintenance_scale.py")
    return pd.read_csv(path)


#: Bound match tolerance for selecting a regime's row out of the CSV. The bounds are written
#: unrounded, so this only absorbs the float round trip through the text file.
_BOUND_TOLERANCE = 1e-9

#: How far a shipped field may sit from a fresh Yeast9 solve. Two sources, both named: the
#: table rounds to six decimals (<= 5e-7), and glpk's simplex settles on optima that differ
#: at ~1e-7 depending on the basis it warm-starts from.
_SOLVE_TOLERANCE = 2e-6


def _row(table, regime):
    """The one row of the CSV at this regime's bounds.

    Not ``== pytest.approx(...)``: on a pandas Series that comparison returns all-False
    rather than an elementwise match, which selects nothing and passes nothing.
    """
    selected = table[
        ((table["glucose_lower_bound_mmol_per_gdcw_h"]
          - regime.glucose_lower_bound_mmol_per_gdcw_h).abs() <= _BOUND_TOLERANCE)
        & ((table["oxygen_lower_bound_mmol_per_gdcw_h"]
            - regime.oxygen_lower_bound_mmol_per_gdcw_h).abs() <= _BOUND_TOLERANCE)]
    assert len(selected) == 1, f"{regime.name} selects {len(selected)} rows, not one"
    return selected.iloc[0]


