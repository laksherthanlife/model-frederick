class TestTheRegimeLabelReadsTheMechanismAndNotTheBound:
    """Overflow is what changes the slope, so the label reads the ethanol exchange. A cell can
    be oxygen-capped and still respire everything it takes up -- glucose -1.0 against oxygen
    -3.7 does exactly that, and calling it fermentative on its oxygen bound would be wrong."""

    def test_zero_ethanol_is_respiratory(self):
        assert regime_label(0.0) == "respiratory"

    def test_a_real_overflow_flux_is_fermentative(self):
        assert regime_label(15.923) == "fermentative"

    def test_solver_noise_is_not_overflow(self):
        assert regime_label(0.1 * ETHANOL_DETECTION_MMOL_PER_GDCW_H) == "respiratory"

    @pytest.mark.parametrize("threshold", [1e-12, 1e-9, 1e-6, 1e-3, 1e-2, 0.1])
    def test_no_label_in_the_table_depends_on_where_the_threshold_sits(self, table, threshold):
        """The free-scalar gate on the one scalar this piece chose.
        ``ETHANOL_DETECTION_MMOL_PER_GDCW_H`` is ASSERTED, so it is swept: every respiratory
        row secretes exactly zero and every fermenting row at least 0.145, so eleven decades
        of threshold assign the same sixteen labels and no result rests on the choice."""
        for row in table.itertuples():
            expected = ("fermentative"
                        if row.ethanol_at_zero_ngam_mmol_per_gdcw_h > threshold
                        else "respiratory")

            assert expected == row.regime


